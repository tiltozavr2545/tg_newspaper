def draw_photos(directory: Path) -> dict[str, str]:
    paths: dict[str, str] = {}
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 1200, "height": 800})
        for name, (c1, c2, shapes) in SCENES.items():
            svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800" viewBox="0 0 1200 800">'
                   f'<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{c1}"/>'
                   f'<stop offset="1" stop-color="{c2}"/></linearGradient></defs>'
                   f'<rect width="1200" height="800" fill="url(#g)"/>{shapes}</svg>')
            page.set_content(f'<body style="margin:0">{svg}</body>')
            out = directory / f"{name}.png"
            page.screenshot(path=str(out))
            paths[name] = str(out)
        browser.close()
    return paths


def stack(top: Path, bottom: Path, out: Path) -> None:
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 1400, "height": 1980})
        html_file = out.parent / "_stack.html"
        html_file.write_text(
            f'<body style="margin:0"><img src="{top.resolve().as_uri()}" style="display:block;width:1400px">'
            f'<img src="{bottom.resolve().as_uri()}" style="display:block;width:1400px"></body>', encoding="utf-8"
        )
        page.goto(html_file.as_uri(), wait_until="load")
        page.screenshot(path=str(out), full_page=True)
        browser.close()
        html_file.unlink()


def main() -> None:
    tmp = Path(tempfile.mkdtemp(prefix="demo_issue_"))
    try:
        photos = draw_photos(tmp)
        now = datetime(2026, 5, 14, 7, 30, tzinfo=timezone.utc)
        posts: list[Post] = []
        importance: dict[tuple[str, int], int] = {}
        relevance: dict[tuple[str, int], int] = {}
        photo_path: dict[tuple[str, int], str] = {}
        for i, (channel, title, body, imp, scene) in enumerate(NEWS, start=1):
            post = Post(channel=channel, message_id=i, posted_at=now - timedelta(minutes=37 * i),
                        text=f"**{title}**\n\n{body}", has_media=scene is not None,
                        media_type="photo" if scene else None)
            posts.append(post)
            key = (channel, i)
            importance[key] = imp
            if scene:
                photo_path[key] = photos[scene]
                relevance[key] = 3 if imp == 5 else 2

        def fake_teasers(ps):
            # Заглушка вместо Gemini: выдуманные «крикливые» анонсы.
            shouts = [("КНИГИ ПОД НЕБОМ!", "Читальня у пруда откроется уже в выходные"),
                      ("ТОМАТ-СТОЙКИЙ!", "Сорт без полива три недели"),
                      ("48 ЧАСОВ БЕЗ РОЗЕТКИ", "Недорогой ноутбук с рекордной батареей"),
                      ("ПЕНАЛЬТИ РЕШИЛИ ВСЁ!", "Кубок района остался дома")]
            return {(p.channel, p.message_id): shouts[i % len(shouts)] for i, p in enumerate(ps)}

        work = tmp / "out"
        pages, _ = render_pages(
            posts, work, run_date=now, page_size="A4", landscape=True, max_pages=4,
            importance_by_key=importance, photo_relevance_by_key=relevance,
            photo_path_by_key=photo_path, issue_number=1, teaser_provider=fake_teasers,
        )
        OUT.mkdir(parents=True, exist_ok=True)
        # Обложка — склеенный лист из двух полос: сшиваем их обратно в одну картинку.
        stack(pages[0], pages[1], OUT / "demo-cover.png")
        # Полоса мозаики — в той же ширине, что обложка: README не нужен 300 dpi.
        subprocess.run(["sips", "-Z", "1400", str(pages[2]), "--out", str(OUT / "demo-page.png")],
                       check=True, capture_output=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
